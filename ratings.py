def get_rating(hotel_name: str):
    """
    Ищет рейтинг отеля по частичному совпадению названия.
    Возвращает (рейтинг, ссылка) или (None, None).
    """
    name = hotel_name.lower()
    # Сначала ищем точное вхождение ключа
    for key, (rating, link) in HOTEL_RATINGS.items():
        if key in name:
            return rating, link
    # Если не нашли — ищем по словам (хотя бы 2 совпадающих слова)
    name_words = set(name.split())
    best_match = None
    best_count = 1  # минимум 2 совпадения
    for key, (rating, link) in HOTEL_RATINGS.items():
        key_words = set(key.split())
        common = len(key_words & name_words)
        if common > best_count:
            best_count = common
            best_match = (rating, link)
    return best_match if best_match else (None, None)
